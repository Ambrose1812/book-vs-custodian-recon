"""Regenerate ci/raw_schema.sql from the local landing zone.

Run from the repo root after adding or changing a data source:
    python ci/make_raw_schema.py

CI has no data (data/ is gitignored and the ingest needs API keys), so it creates
empty raw tables from this file. The column types are produced by the same pandas
code path the loader uses (DataFrame.to_sql), so they match what a real load creates.
"""
import datetime
import sys
from pathlib import Path

import pandas as pd
from pandas.io.sql import SQLTable
from sqlalchemy import MetaData
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateTable

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "ingest"))
from load_to_postgres import SCHEMA, SOURCES  # noqa: E402  (the loader's own source list)


class _Db:
    """The two attributes pandas' SQLTable needs to build a table without a connection."""
    def __init__(self):
        self.meta = MetaData(schema=SCHEMA)
        self.con = None


def main():
    lines = ["-- Empty raw tables with the same columns and types the loader creates.",
             "-- Generated by ci/make_raw_schema.py from the landing zone. Used only by CI.",
             f"create schema if not exists {SCHEMA};", ""]
    for label, landing_dir, table in SOURCES:
        files = sorted(landing_dir.glob("ingest_date=*/*.parquet"))
        if not files:
            raise SystemExit(f"No landing data for {label}: run the pipeline locally first.")
        df = pd.read_parquet(files[-1]).head(5).assign(_source_file="x")
        df["ingest_date"] = datetime.date(2026, 1, 1)            # what the loader adds
        df["_loaded_at"] = pd.Timestamp.now(tz="UTC")
        t = SQLTable(table, _Db(), frame=df, index=False, schema=SCHEMA)
        ddl = str(CreateTable(t.table).compile(dialect=postgresql.dialect())).strip()
        ddl = "\n".join(line.rstrip() for line in ddl.splitlines())
        lines.append(ddl.replace("CREATE TABLE", "create table if not exists", 1) + ";\n")
    (ROOT / "ci" / "raw_schema.sql").write_text("\n".join(lines))
    print(f"Wrote ci/raw_schema.sql ({len(SOURCES)} tables)")


if __name__ == "__main__":
    main()
